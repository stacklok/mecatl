func TestIncludeSelection(t *testing.T) {
	for _, tc := range []struct {
		name, source, reason string
		types                []string
	}{
		{"missing", "type Record struct{}", "select at least one root", nil},
		{"mixed", "//dtogen:include\ntype Record struct{}", "cannot be combined", []string{"Record"}},
		{"duplicate", "//dtogen:include\n//dtogen:include\ntype Record struct{}", "duplicate", nil},
		{"argument", "//dtogen:include Record\ntype Record struct{}", "invalid or unknown", nil},
		{"equals", "//dtogen:include=true\ntype Record struct{}", "invalid or unknown", nil},
		{"misplaced", "//dtogen:include\nfunc f(){}", "ambiguous or misplaced", nil},
		{"detached", "//dtogen:include\n\ntype Record struct{}", "ambiguous or misplaced", nil},
		{"field", "type Record struct {\n//dtogen:include\nV string\n}", "ambiguous or misplaced", nil},
		{"trailing", "type Record struct{} //dtogen:include", "ambiguous or misplaced", nil},
		{"ambiguous", "//dtogen:include\ntype (Record struct{}; Other struct{})", "ambiguous or misplaced", nil},
		{"alias", "//dtogen:include\ntype Record = string", "not an alias", nil},
		{"invalid explicit", "type Record struct{}", "must name a local type", []string{""}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "owner.go")
			writeFixture(t, path, "package owner\n"+tc.source)
			_, err := sourceOwner([]string{path}, filepath.Join(dir, "generated.go"), tc.types, capabilities{clone: true})
			if err == nil || !strings.Contains(err.Error(), tc.reason) {
				t.Fatalf("got %v; want %q", err, tc.reason)
			}
		})
	}
	// A grouped type's own doc selects only that type. Unmarked children remain
	// in the operation closure, and other marked roots sort independently.
	dir := t.TempDir()
	path := filepath.Join(dir, "owner.go")
	writeFixture(t, path, `package owner
//dtogen:include
type Zulu struct { Child Child }
type (
 //dtogen:include
 Alpha string
 Child struct { Value string }
 Unused struct{}
)
`)
	owner, err := sourceOwner([]string{path}, "", nil, capabilities{clone: true})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(owner.Config.Types, []string{"Alpha", "Zulu"}) || !slices.Equal(owner.Names, []string{"Alpha", "Child", "Zulu"}) {
		t.Fatalf("roots %v; closure %v", owner.Config.Types, owner.Names)
	}
}

func TestIncludeValueRoots(t *testing.T) {
	cfg := executableFixture(t, `
//dtogen:include
//dtogen:validate valid
//dtogen:override Clone
type Zulu struct { Child Child `+"`cbor:\"child\"`"+`; Generated Generated `+"`cbor:\"generated\"`"+` }
func(Zulu)valid()error{return nil}
func(v Zulu)Clone()Zulu{return Zulu{Child:v.Child.Clone(),Generated:v.Generated.Clone()}}
type Child struct { Value string `+"`cbor:\"value\"`"+` }
//dtogen:include
type Alpha string
type Unused struct { Unsupported chan int }
func init(){panic("owner executed")}
var _ = Zulu{}.Clone().Equal(Zulu{})
`)
	cfg.Types = nil
	cfg.Emit = "cbor,clone,equal"
	root := filepath.Dir(filepath.Dir(cfg.Dir))
	writeFixture(t, filepath.Join(cfg.Dir, "registry.go"), "//go:generate go -C ../.. run "+generatorCommand+" -dir engine/owner -emit "+cfg.Emit+" -out "+cfg.Output+"\npackage owner\n")
	// A generated sibling's declarations remain part of the package and can be
	// reached from a handwritten root, but its dtogen annotations are inert.
	siblingPath := filepath.Join(cfg.Dir, "other_generated.go")
	writeFixture(t, siblingPath, `// Code generated by siblinggen. DO NOT EDIT.
package owner
//dtogen:include
type Generated struct { Value string `+"`cbor:\"value\"`"+` }
//dtogen:include malformed
type Poison struct{}
`)
	sibling := readFixture(t, siblingPath)
	// Neither inactive nor test-only directives can add roots or poison selection.
	writeFixture(t, filepath.Join(cfg.Dir, "inactive.go"), "//go:build ignore\n\npackage owner\n//dtogen:include invalid\ntype Inactive = Missing\n")
	writeFixture(t, filepath.Join(cfg.Dir, "owner_test.go"), "package owner\n//dtogen:include invalid\ntype TestOnly = Missing\n")
	ctx := context.Background()
	loaded, err := Load(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	var roots []string
	for _, named := range loaded.Roots {
		roots = append(roots, named.Obj().Name())
	}
	if !slices.Equal(roots, []string{"Alpha", "Zulu"}) || !slices.Equal(loaded.Owners[loaded.Package.PkgPath].Names, []string{"Alpha", "Child", "Generated", "Zulu"}) {
		t.Fatalf("roots %v; owner %+v", roots, loaded.Owners[loaded.Package.PkgPath])
	}
	if err := Generate(ctx, cfg); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(cfg.Dir, cfg.Output)
	first := readFixture(t, out)
	if !strings.Contains(first, "func (v Child) Clone() Child") || !strings.Contains(first, "func (v Generated) Clone() Generated") || strings.Contains(first, "func (v Unused)") {
		t.Fatal("wrong selected closure")
	}
	if err := GenerateRepository(ctx, root, true); err != nil {
		t.Fatal(err)
	}
	if err := GenerateRepository(ctx, root, false); err != nil {
		t.Fatal(err)
	}
	if first != readFixture(t, out) {
		t.Fatal("direct and repository output disagree")
	}
	// Marker order and explicit selection produce the same generated value API.
	path := filepath.Join(cfg.Dir, "owner.go")
	source := readFixture(t, path)
	writeFixture(t, path, strings.ReplaceAll(source, "//dtogen:include\n", ""))
	cfg.Types = []string{"Zulu", "Alpha", "Zulu"}
	if err := Generate(ctx, cfg); err != nil {
		t.Fatal(err)
	}
	if first != readFixture(t, out) {
		t.Fatal("marker and explicit output disagree")
	}
	writeFixture(t, path, source)
	before := repositoryState(t, root)
	if err := Generate(ctx, cfg); err == nil || !strings.Contains(err.Error(), "cannot be combined") {
		t.Fatal("mixed selection accepted", err)
	}
	if !reflect.DeepEqual(before, repositoryState(t, root)) {
		t.Fatal("mixed selection changed artifacts")
	}
	cfg.Types = nil
	writeFixture(t, path, strings.Replace(source, "//dtogen:include", "//dtogen:include extra", 1))
	before = repositoryState(t, root)
	for _, generate := range []func() error{
		func() error { return Generate(ctx, cfg) },
		func() error { return GenerateRepository(ctx, root, false) },
	} {
		if err := generate(); err == nil || !strings.Contains(err.Error(), "invalid or unknown") {
			t.Fatal("malformed active marker accepted", err)
		}
		if !reflect.DeepEqual(before, repositoryState(t, root)) {
			t.Fatal("malformed marker changed artifacts")
		}
	}
	// Generated and handwritten siblings still participate in strict type checking.
	writeFixture(t, path, source)
	writeFixture(t, siblingPath, sibling+"\nvar _ = MissingGenerated\n")
	if _, err := Load(ctx, cfg); err == nil || !strings.Contains(err.Error(), "undefined: MissingGenerated") {
		t.Fatal("generated compile error hidden", err)
	}
	writeFixture(t, siblingPath, sibling)
	writeFixture(t, path, source+"\nvar _ = MissingHandwritten\n")
	if _, err := Load(ctx, cfg); err == nil || !strings.Contains(err.Error(), "undefined: MissingHandwritten") {
		t.Fatal("handwritten compile error hidden", err)
	}
}

func TestIncludeViewBootstrap(t *testing.T) {
	cfg := viewFixture(t, "view")
	cfg.Types = nil
	root := filepath.Dir(filepath.Dir(cfg.Dir))
	// The DTO owner is an imported prerequisite selected by its own marker.
	writeFixture(t, filepath.Join(filepath.Dir(cfg.Dir), "data/value.go"), `package data
//dtogen:include
type Record struct { Title string; Child Child }
type Child struct { Label string }
func init(){panic("DTO owner executed")}
var _ = Record{}.Clone()
`)
	writeFixture(t, filepath.Join(filepath.Dir(cfg.Dir), "data/registry.go"), "//go:generate go -C ../.. run "+generatorCommand+" -dir engine/data -emit clone,equal -out zz_data_generated.go\npackage data\n")
	writeFixture(t, filepath.Join(cfg.Dir, "owner.go"), `package owner
import "github.com/stacklok/mecatl/engine/data"
//dtogen:include
type RecordView struct { value *data.Record; scope string }
//dtogen:include
type ChildView struct { value *data.Child }
func init(){panic("view owner executed")}
var _ = RecordView{}.Title()
var _ = RecordView{}.Child().Label()
`)
	writeFixture(t, filepath.Join(cfg.Dir, "registry.go"), "//go:generate go -C ../.. run "+generatorCommand+" -dir engine/owner -emit view -out "+cfg.Output+"\npackage owner\n")
	outputs := []string{filepath.Join(cfg.Dir, cfg.Output), filepath.Join(filepath.Dir(cfg.Dir), "data/zz_data_generated.go")}
	ctx := context.Background()
	for _, prior := range []string{"", GeneratedMarker + "\nnot Go", GeneratedMarker + "\npackage owner\n//dtogen:include invalid\ntype Poison = Missing"} {
		for _, out := range outputs {
			if prior != "" {
				writeFixture(t, out, prior)
			}
		}
		before := repositoryState(t, root)
		if err := GenerateRepository(ctx, root, true); err == nil {
			t.Fatal("missing/corrupt artifacts accepted")
		}
		if !reflect.DeepEqual(before, repositoryState(t, root)) {
			t.Fatal("check installed bootstrap artifacts")
		}
		loaded, err := Load(ctx, cfg)
		if err != nil {
			t.Fatal(err)
		}
		if len(loaded.Roots) != 0 || len(loaded.Prerequisites) != 1 || loaded.Prerequisites[0].Roots[0].Obj().Name() != "Record" {
			t.Fatalf("view roots/prerequisites: %+v", loaded)
		}
		if !slices.Equal(loaded.Owners[loaded.Package.PkgPath].Config.Types, []string{"ChildView", "RecordView"}) {
			t.Fatal("view selection not resolved/sorted")
		}
		if err := Generate(ctx, cfg); err != nil {
			t.Fatal(err)
		}
		if err := GenerateRepository(ctx, root, true); err != nil {
			t.Fatal(err)
		}
	}
	// A handwritten error still fails the strict load; neither owner is installed.
	writeFixture(t, filepath.Join(cfg.Dir, "broken.go"), "package owner\nvar broken string = RecordView{}.Child().Label() + 1\n")
	before := repositoryState(t, root)
	if err := Generate(ctx, cfg); err == nil || !strings.Contains(err.Error(), "mismatched types") {
		t.Fatal("handwritten error hidden by bootstrap", err)
	}
	if !reflect.DeepEqual(before, repositoryState(t, root)) {
		t.Fatal("failed closure changed artifacts")
	}
}

func TestIncludeCLIAndDirectiveSelection(t *testing.T) {
	binary := buildCLI(t)
	cfg := moduleFixture(t, "//dtogen:include\ntype Record struct{ Value string }")
	cfg.Types = nil
	cfg.Emit = "clone,equal"
	root := filepath.Dir(filepath.Dir(cfg.Dir))
	base := []string{"-dir", cfg.Dir, "-emit", cfg.Emit, "-out", cfg.Output}
	for _, tc := range []struct {
		name string
		args []string
		want bool
	}{
		{"omitted", nil, true},
		{"empty", []string{"-types="}, false},
		{"empty separate", []string{"-types", ""}, false},
		{"mixed", []string{"-types", "Record"}, false},
		{"repository empty", []string{"-repo", root, "-types="}, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			args := append(slices.Clone(base), tc.args...)
			if tc.name == "repository empty" {
				args = tc.args
			}
			before := repositoryState(t, root)
			cmd := exec.Command(binary, args...)
			cmd.Dir = t.TempDir()
			cmd.Env = loadEnvironment()
			out, err := cmd.CombinedOutput()
			if (err == nil) != tc.want {
				t.Fatalf("got %s, %v; success=%v", out, err, tc.want)
			}
			if !tc.want && !reflect.DeepEqual(before, repositoryState(t, root)) {
				t.Fatal("invalid CLI changed artifacts")
			}
		})
	}
	for _, flags := range [][]string{nil, {"-types="}, {"-types", ""}} {
		words := append([]string{"go", "-C", "../..", "run", generatorCommand, "-dir", "engine/owner", "-emit", cfg.Emit, "-out", cfg.Output}, flags...)
		target, err := directiveTarget(root, cfg.Dir, words)
		if len(flags) == 0 {
			if err != nil || len(target.Types) != 0 {
				t.Fatalf("omitted directive selection: %+v, %v", target, err)
			}
		} else if err == nil || !strings.Contains(err.Error(), "explicit -types must not be empty") {
			t.Fatalf("empty explicit directive accepted: %v", err)
		}
	}
	// Empty explicit selection must be invalid even without markers.
	writeFixture(t, filepath.Join(cfg.Dir, "owner.go"), "package owner\ntype Record struct{}\n")
	for _, args := range [][]string{base, append(slices.Clone(base), "-types=")} {
		cmd := exec.Command(binary, args...)
		cmd.Env = os.Environ()
		if out, err := cmd.CombinedOutput(); err == nil {
			t.Fatalf("missing/empty selection accepted without markers: %s", out)
		}
	}
}
