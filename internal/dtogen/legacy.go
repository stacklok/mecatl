package dtogen

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const legacyGeneratedMarker = "// Code generated by cborgen. DO NOT EDIT."

// legacyOutput permits only the pre-rename artifacts in the engine module.
// The old marker is not a general opt-in for new owners or arbitrary filenames.
func legacyOutput(path string) bool {
	if filepath.Base(path) != "zz_cbor_generated.go" {
		return false
	}
	for dir := filepath.Dir(path); ; dir = filepath.Dir(dir) {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil {
			if !strings.HasPrefix(string(data), "module github.com/stacklok/mecatl/engine\n") {
				return false
			}
			rel, err := filepath.Rel(dir, filepath.Dir(path))
			return err == nil && slices.Contains([]string{
				"id", "kernel/codec/internal/fixture", "kernel/codec/internal/fixture/value",
				"kernel/contentid", "kernel/history/id", "kernel/history/format", "kernel/session/format",
			}, filepath.ToSlash(rel))
		}
		if !os.IsNotExist(err) || filepath.Dir(dir) == dir {
			return false
		}
	}
}
