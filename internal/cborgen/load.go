// Package cborgen statically loads owner declarations for persistence-codec generation.
package cborgen

import (
	"context"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"golang.org/x/tools/go/packages"
)

// GeneratedMarker identifies artifacts owned by cborgen.
const GeneratedMarker = "// Code generated by cborgen. DO NOT EDIT."

const codecImportPath = "github.com/stacklok/mecatl/engine/kernel/codec"

// LoadConfig selects one declaring package and its package-local output file.
type LoadConfig struct {
	Dir    string
	Types  []string
	Output string
}

// Loaded contains type information from a synthetic public-entry-point overlay.
// The overlay is load-only: it is never written or executed. Schema validation
// and emission must complete before a caller replaces Output.
type Loaded struct {
	Package       *packages.Package
	Roots         []*types.Named // sorted, deduplicated local nongeneric roots
	Output        string         // absolute output pathname; Load does not modify it
	Owners        map[string]*ownerDeclaration
	Validators    map[string]string
	Prerequisites []*Loaded // dependency order, excluding this package
}

// Load loads from Dir's containing module, independently of any ambient workspace.
// Declared owner artifacts are replaced by load-only signatures; handwritten
// diagnostics remain fatal. Imported families are validated from their sources.
func Load(ctx context.Context, config LoadConfig) (*Loaded, error) {
	dir, err := filepath.Abs(config.Dir)
	if err != nil {
		return nil, err
	}
	out := config.Output
	if !validOutputName(out) {
		return nil, fmt.Errorf("output must be a package-local non-test Go filename")
	}
	out = filepath.Join(dir, out)
	if _, err := readOutput(out); err != nil {
		return nil, err
	}
	names := slices.Clone(config.Types)
	slices.Sort(names)
	names = slices.Compact(names)
	if len(names) == 0 {
		return nil, fmt.Errorf("select at least one root type")
	}
	for _, name := range names {
		if !token.IsIdentifier(name) || name == "_" {
			return nil, fmt.Errorf("root %q must name a local type", name)
		}
	}
	// Exclude the artifact for metadata discovery, so Go selects the active
	// handwritten files and package name using the real build context. This pass
	// cannot type check callers until the artifact's public API has been stubbed.
	targets, err := ownerTargets(dir, config)
	if err != nil {
		return nil, err
	}
	overlay := map[string][]byte{}
	for _, target := range targets {
		path := filepath.Join(target.Dir, target.Output)
		if _, err := readOutput(path); err != nil {
			return nil, err
		}
		overlay[path] = []byte("//go:build ignore\n\npackage ignored\n")
	}
	cfg := &packages.Config{
		Context: ctx,
		Dir:     dir,
		Env:     loadEnvironment(),
		Mode:    packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedModule,
		Overlay: overlay,
	}
	metadata, err := loadOne(cfg)
	if err != nil {
		return nil, err
	}
	if metadata.Module == nil {
		return nil, fmt.Errorf("declaring package must belong to a Go module")
	}
	if err := checkDeclarations(metadata.CompiledGoFiles, out, names); err != nil {
		return nil, err
	}
	owners, overlay, err := ownerOverlays(ctx, targets, overlay)
	if err != nil {
		return nil, err
	}
	cfg.Overlay = overlay
	cfg.Mode |= packages.NeedTypes | packages.NeedTypesInfo | packages.NeedSyntax | packages.NeedImports | packages.NeedDeps
	pkg, err := loadOne(cfg)
	if err != nil {
		return nil, err
	}
	if !slices.Contains(pkg.CompiledGoFiles, out) {
		return nil, fmt.Errorf("output %s is not an active package Go file", out)
	}
	loaded, err := selectedRoots(pkg, out, names)
	if err != nil {
		return nil, err
	}
	loaded.Owners = owners
	loaded.Validators = owners[pkg.PkgPath].Validators
	if err := loaded.loadPrerequisites(); err != nil {
		return nil, err
	}
	return loaded, nil
}

// loadPrerequisites validates imported owners against their loaded source and
// records the actual named wire/value closure in dependency order.
func (loaded *Loaded) loadPrerequisites() error {
	pkg, owners := loaded.Package, loaded.Owners
	var dependencyError error
	visitDependencies(pkg, func(dependency *packages.Package) {
		if dependency == pkg || dependencyError != nil {
			return
		}
		owner := owners[dependency.PkgPath]
		if owner == nil {
			return
		}
		output := filepath.Join(owner.Config.Dir, owner.Config.Output)
		if !slices.Contains(dependency.CompiledGoFiles, output) {
			dependencyError = fmt.Errorf("%s: declared owner at %s is not the imported source package; use the owner's module/build context", dependency.PkgPath, owner.Config.Dir)
			return
		}
		child, err := selectedRoots(dependency, output, owner.Config.Types)
		if err != nil {
			dependencyError = err
			return
		}
		child.Owners = owners
		child.Validators = owner.Validators
		s, err := buildSchema(child)
		if err != nil {
			dependencyError = err
			return
		}
		owner.Wire = map[string]bool{}
		owner.Names = nil
		for _, n := range s.nodes {
			if named, ok := n.typ.(*types.Named); ok && named.Obj().Pkg() == dependency.Types {
				owner.Wire[named.Obj().Name()] = n.wire
				owner.Names = append(owner.Names, named.Obj().Name())
			}
		}
		slices.Sort(owner.Names)
		loaded.Prerequisites = append(loaded.Prerequisites, child)
	})
	return dependencyError
}

func validOutputName(name string) bool {
	return filepath.Base(name) == name && strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") && !strings.HasPrefix(name, ".") && !strings.HasPrefix(name, "_")
}

func selectedRoots(pkg *packages.Package, out string, names []string) (*Loaded, error) {
	loaded := &Loaded{Package: pkg, Output: out}
	for _, name := range names {
		obj, ok := pkg.Types.Scope().Lookup(name).(*types.TypeName)
		if !ok || obj.IsAlias() {
			return nil, fmt.Errorf("root %s must be a locally defined type, not an alias", name)
		}
		named, ok := obj.Type().(*types.Named)
		if !ok || named.Obj().Pkg() != pkg.Types || named.TypeParams().Len() != 0 {
			return nil, fmt.Errorf("root %s must be locally defined and nongeneric", name)
		}
		loaded.Roots = append(loaded.Roots, named)
	}
	return loaded, nil
}

func loadEnvironment() []string {
	env := slices.DeleteFunc(os.Environ(), func(value string) bool { return strings.HasPrefix(value, "GOWORK=") })
	return append(env, "GOWORK=off")
}

func loadOne(cfg *packages.Config) (*packages.Package, error) {
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	var diagnostics []string
	packages.Visit(pkgs, nil, func(pkg *packages.Package) {
		for _, diagnostic := range pkg.Errors {
			diagnostics = append(diagnostics, diagnostic.Error())
		}
	})
	if len(diagnostics) != 0 {
		return nil, fmt.Errorf("package load:\n%s", strings.Join(diagnostics, "\n"))
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("expected one declaring package, got %d", len(pkgs))
	}
	return pkgs[0], nil
}

func checkFileDeclarations(file *ast.File, fset *token.FileSet, selected map[string]*ast.TypeSpec, reserved map[string]bool) error {
	collision := func(name *ast.Ident) error {
		if types.Universe.Lookup(name.Name) != nil {
			return fmt.Errorf("%s: handwritten declaration shadows predeclared %s required by generated code", fset.Position(name.Pos()), name.Name)
		}
		return fmt.Errorf("%s: handwritten declaration collides with generated %s", fset.Position(name.Pos()), name.Name)
	}
	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				var identifiers []*ast.Ident
				switch spec := spec.(type) {
				case *ast.TypeSpec:
					identifiers = []*ast.Ident{spec.Name}
					if _, ok := selected[spec.Name.Name]; ok {
						selected[spec.Name.Name] = spec
					}
				case *ast.ValueSpec:
					identifiers = spec.Names
				}
				for _, name := range identifiers {
					if reserved[name.Name] {
						return collision(name)
					}
				}
			}
		case *ast.FuncDecl:
			if decl.Recv == nil {
				if reserved[decl.Name.Name] {
					return collision(decl.Name)
				}
			} else if generatedMethod(decl.Name.Name) {
				receiver := decl.Recv.List[0].Type
				if pointer, ok := receiver.(*ast.StarExpr); ok {
					receiver = pointer.X
				}
				if name, ok := receiver.(*ast.Ident); ok {
					if _, ok := selected[name.Name]; ok {
						return collision(decl.Name)
					}
				}
			}
		}
	}
	return nil
}

func checkDeclarations(files []string, out string, roots []string) error {
	selected := make(map[string]*ast.TypeSpec, len(roots))
	reserved := make(map[string]bool, 3*len(roots))
	// Generated code must use actual language primitives, never owner hooks or
	// shadowed scalar names. Check before loading the public-entry-point stubs.
	for _, name := range []string{"append", "bool", "byte", "error", "false", "int", "int8", "int16", "int32", "int64", "len", "make", "min", "nil", "panic", "string", "true", "uint8", "uint16", "uint32", "uint64"} {
		reserved[name] = true
	}
	for _, root := range roots {
		selected[root] = nil
	}
	fset := token.NewFileSet()
	for _, path := range files {
		if path == out {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		if err := checkFileDeclarations(file, fset, selected, reserved); err != nil {
			return err
		}
	}
	for _, root := range roots {
		spec := selected[root]
		if spec == nil {
			return fmt.Errorf("root %s is not a locally declared type", root)
		}
		if spec.Assign.IsValid() {
			return fmt.Errorf("root %s is an alias; select a locally defined struct", root)
		}
		if spec.TypeParams != nil {
			return fmt.Errorf("root %s is generic; select a nongeneric struct", root)
		}
		if structure, ok := spec.Type.(*ast.StructType); ok {
			for _, field := range structure.Fields.List {
				for _, name := range field.Names {
					if generatedMethod(name.Name) {
						return fmt.Errorf("%s: field %s collides with generated method", fset.Position(name.Pos()), name.Name)
					}
				}
			}
		}
	}
	return nil
}
