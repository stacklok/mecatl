package cborgen

import (
	"context"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// assertHelperNamespace checks declarations, not text that could match call sites.
func assertHelperNamespace(t *testing.T, cfg LoadConfig, wantAliases bool) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(cfg.Dir, cfg.Output))
	if err != nil {
		t.Fatal(err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), cfg.Output, data, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	impl := "cborgen"
	numeric := regexp.MustCompile(`^(clone|equal|check|append|read)[0-9]+$`)
	methods, implementations, aliases := 0, 0, 0
	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.FuncDecl:
			if decl.Recv == nil {
				if !ast.IsExported(decl.Name.Name) {
					t.Errorf("package-scope private helper %s", decl.Name.Name)
				}
				continue
			}
			receiver, ok := decl.Recv.List[0].Type.(*ast.Ident)
			if !ok {
				t.Fatalf("unexpected receiver %T", decl.Recv.List[0].Type)
			}
			if receiver.Name == impl {
				methods++
				if !numeric.MatchString(decl.Name.Name) {
					t.Errorf("non-numeric helper %s", decl.Name.Name)
				}
			} else if decl.Name.Name != "Clone" && decl.Name.Name != "Equal" {
				t.Errorf("helper on unexpected receiver %s", receiver.Name)
			}
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				spec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				switch {
				case spec.Name.Name == impl:
					implementations++
					structure, ok := spec.Type.(*ast.StructType)
					if !ok || len(structure.Fields.List) != 0 {
						t.Fatal("implementation is not stateless")
					}
				case spec.Name.Name == impl+"Policy":
				case strings.HasPrefix(spec.Name.Name, impl+"Value") && spec.Assign.IsValid():
					aliases++
				default:
					t.Errorf("unexpected package type %s", spec.Name.Name)
				}
			}
		}
	}
	if implementations != 1 || methods == 0 || (aliases > 0) != wantAliases {
		t.Fatalf("implementations=%d methods=%d aliases=%d (want aliases=%v)", implementations, methods, aliases, wantAliases)
	}
	return string(data)
}

func TestGenerateMultipleRootsShareImplementation(t *testing.T) {
	cfg := executableFixture(t, `
import "github.com/stacklok/mecatl/engine/values"
type v []byte
type out uint32
type limits struct { P map[string][]v `+"`cbor:\"p\"`"+`; O []out `+"`cbor:\"o\"`"+` }
type Record struct {
 V limits `+"`cbor:\"v\"`"+`
 A struct { Text values.Text `+"`cbor:\"text\"`"+` } `+"`cbor:\"a\"`"+`
 X []out `+"`cbor:\"-\"`"+`
}
type Other struct { V limits `+"`cbor:\"v\"`"+`; T values.Text `+"`cbor:\"t\"`"+` }
// These former package helper names no longer pollute the owner's namespace.
var cborgenClone0, cborgenCheck0, cborgenValue0 bool
`)
	writeFixture(t, filepath.Join(filepath.Dir(cfg.Dir), "values/value.go"), "package values\ntype Text string\n")
	cfg.Types = []string{"Record", "Other"}
	if err := Generate(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}
	first := assertHelperNamespace(t, cfg, true)
	for _, shape := range []string{"values.Text", "map[string][]v", "[]out"} {
		if !strings.Contains(first, ": "+shape+".") {
			t.Errorf("missing concrete type mapping for %s", shape)
		}
	}
	if !strings.Contains(first, ": struct{Text values.Text") {
		t.Fatal("missing anonymous shape mapping")
	}
	writeFixture(t, filepath.Join(cfg.Dir, "callers.go"), `package owner
import "github.com/stacklok/mecatl/engine/kernel/codec"
func roundTrip(v Record,l codec.Limits) bool { b,e:=EncodeRecord(v.Clone(),l);if e!=nil{return false};w,e:=DecodeRecord(b,l);return e==nil&&CheckRecord(w,l)==nil&&v.Equal(w) }
func (v Other) roundTrip(l codec.Limits) bool {b,e:=EncodeOther(v.Clone(),l);if e!=nil{return false};w,e:=DecodeOther(b,l);return e==nil&&CheckOther(w,l)==nil&&v.Equal(w)}
`)
	writeFixture(t, filepath.Join(cfg.Dir, "owner_test.go"), `package owner
import("testing";"github.com/stacklok/mecatl/engine/kernel/codec")
func TestBothRoots(t *testing.T) {
 l:=codec.Limits{MaxBytes:10000,MaxStringBytes:100,MaxByteStringBytes:100,MaxArrayElements:100,MaxMapPairs:100,MaxDepth:20,MaxNodes:1000,MaxCollectionElements:1000}
 a:=Record{V:limits{P:map[string][]v{"x":{{1,2}}},O:[]out{3}}};a.A.Text="text"
 if !roundTrip(a,l)||!(Other{V:a.V,T:"text"}).roundTrip(l){t.Fatal("generated root APIs")}
 a.X=[]out{4};b:=a.Clone();b.X[0]=5;b.V.P["x"][0][0]=9;b.V.O[0]=6
 if a.X[0]!=4||a.V.P["x"][0][0]!=1||a.V.O[0]!=3||a.Equal(b){t.Fatal("whole value clone/equal ownership")}
}
`)
	runOwner(t, cfg, "")
	if err := Generate(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}
	if after := assertHelperNamespace(t, cfg, true); first != after {
		t.Fatal("regeneration changed output")
	}
	// Output filenames do not affect the implementation type or generated bytes.
	if err := os.Remove(filepath.Join(cfg.Dir, cfg.Output)); err != nil {
		t.Fatal(err)
	}
	cfg.Output = "zz_other.go"
	if err := Generate(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}
	if after := assertHelperNamespace(t, cfg, true); first != after {
		t.Fatal("output filename changed generated bytes")
	}
	runOwner(t, cfg, "")
}

func TestGenerateUsesConcreteTypesWithoutAliases(t *testing.T) {
	cfg := executableFixture(t, `
type Child struct { S string `+"`cbor:\"s\"`"+` }
type Record struct {
 V map[string][]*Child `+"`cbor:\"v\"`"+`
 A struct { Bytes []byte `+"`cbor:\"bytes\"`"+` } `+"`cbor:\"a\"`"+`
}
`)
	if err := Generate(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}
	assertHelperNamespace(t, cfg, false)
	runOwner(t, cfg, "")
}
